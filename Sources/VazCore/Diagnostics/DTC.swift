import Foundation

/// Diagnostic trouble code from `58 N {hi lo status}×N`; the code is BCD (`01 20` = P0120).
public struct DTC: Equatable, Sendable, Identifiable {
    public let raw: UInt16
    public let status: UInt8

    public var id: UInt16 { raw }
    /// "P0120"; the top two bits select P/C/B/U as in SAE J2012.
    public var code: String {
        let letter = ["P", "C", "B", "U"][Int(raw >> 14)]
        return letter + String(format: "%04X", raw & 0x3FFF)
    }

    public var description: String { Self.descriptions[raw] ?? Self.generalDescriptions[raw] ?? "Неизвестный код" }

    /// Bit 7 of the status byte. Observed on J5V05L19 in the emulator: P0122 (TPS) comes as E0,
    /// P1602 (supply loss) as 60, both unchanged long after the sensor is back — consistent with
    /// ISO 14230-3 «warning lamp» in bit 7 (the standard itself is not at hand; bits 5–6 were
    /// always set and are not interpreted).
    public var lampOn: Bool { status & 0x80 != 0 }

    static func parse(response d: [UInt8]) throws -> [DTC] {
        guard d.first == 0x58, d.count >= 2 else { throw KWPError.unexpectedResponse(d) }
        let n = Int(d[1])
        guard d.count >= 2 + n * 3 else { throw KWPError.unexpectedResponse(d) }
        return (0..<n).map { i in
            let o = 2 + i * 3
            return DTC(raw: UInt16(d[o]) << 8 | UInt16(d[o + 1]), status: d[o + 2])
        }
    }

